_STOPWORDS_FOR_TOPIC = {
    "анекдот", "анекдоты", "анекдота", "анекдоте", "анекдотов",
    "шутка", "шутку", "шути", "пошути", "шуточку",
    "расскажи", "про", "на", "тему", "мне", "какой-нибудь", "что-нибудь",
    "смешное", "смешной", "юмор", "юмора",
}


def _extract_topic_tokens(query: str) -> list[str]:
    tokens = re.findall(r"[а-яёa-z]+", query.lower())
    return [t for t in tokens if t not in _STOPWORDS_FOR_TOPIC]


def _stems_match(a: str, b: str) -> bool:
    """Грубое сравнение по корню слова — чтобы падежные окончания (тёща/тёщу/тёщей)
    не мешали находить совпадение тем."""
    min_len = min(len(a), len(b))
    if min_len < 3:
        return a == b
    stem_len = max(3, min_len - 2)
    return a[:stem_len] == b[:stem_len]


def get_joke(query: str, exclude_texts: set[str] | None = None) -> str:
    """
    Возвращает готовый анекдот из курируемой базы. Если в запросе явно названа тема
    (например "анекдот про тёщу") — пытается подобрать анекдот с подходящим тегом.
    exclude_texts — тексты анекдотов, которые уже рассказывали в этом диалоге недавно,
    чтобы не повторяться подряд.
    """
    exclude_texts = exclude_texts or set()
    topic_tokens = _extract_topic_tokens(query)

    candidates = JOKES
    if topic_tokens:
        matched = [
            j for j in JOKES
            if any(_stems_match(tag, tok) for tag in j["tags"] for tok in topic_tokens)
        ]
        if matched:
            candidates = matched

    fresh = [j for j in candidates if j["text"] not in exclude_texts]
    pool = fresh if fresh else candidates

    return random.choice(pool)["text"]
